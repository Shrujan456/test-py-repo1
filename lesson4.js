//Relational or comparison operators

// > more than
// < less than
// >= more than or equal to
// <= less than or equal to
// == equal to
// != not equal to

var result = 10 > 5
console.log(result) //true, which is a logical operator in boolean data type

var result2 = 5 > 5
console.log(result2)  //false

var result3 = 5 >= 5
console.log(result3)  //true

//Equality operators

var x = 1
console.log(x == '1') //true
console.log(x === '1') //false, because the data type is different 